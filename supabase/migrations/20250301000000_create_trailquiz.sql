-- Trial quiz responses: stores model response + user answers per trial user
create table if not exists public.trailquiz (
  id bigint generated by default as identity not null,
  userid bigint null,
  responcemodel json null,
  created_at timestamp with time zone not null default now(),
  constraint trailquiz_pkey primary key (id),
  constraint trailquiz_userid_fkey foreign key (userid) references public.trailpeoples (id)
) tablespace pg_default;

