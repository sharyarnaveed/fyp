-- Trial feedback: one row per feedback submission from a trial user after quiz
create table if not exists public.trailfeedback (
  id bigint generated by default as identity not null,
  userid bigint null,
  feedback text null,
  created_at timestamp with time zone not null default now(),
  constraint trailfeedback_pkey primary key (id),
  constraint trailfeedback_userid_fkey foreign key (userid) references public.trailpeoples (id)
) tablespace pg_default;
